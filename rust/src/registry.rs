//! Encoding registry with metadata for all supported encodings.
//!
//! The entries mirror `chardet/registry.py` (chardet 7.7.0): canonical names
//! are Python codec names, aliases are the names callers may pass in, and
//! `superset` records the Windows/CP code page that stands in for an
//! encoding in practice.

use crate::enums::EncodingEra;
use once_cell::sync::Lazy;
use std::collections::{HashMap, HashSet};

/// Metadata for a single encoding.
#[derive(Clone, Debug)]
pub struct EncodingInfo {
    /// Canonical encoding name (a Python codec name).
    pub name: &'static str,
    /// Known aliases for this encoding.
    pub aliases: &'static [&'static str],
    /// Which era this encoding belongs to.
    pub era: EncodingEra,
    /// Whether the encoding has the CJK byte structure the structural stage
    /// probes and the CJK gate requires.  Off for UTF-8/16/32, which spend
    /// more than one byte per character but are handled by their own stages.
    pub is_multibyte_cjk: bool,
    /// Languages supported by this encoding (ISO 639-1 codes).
    pub languages: &'static [&'static str],
    /// Windows/CP code page standing in for this encoding, if any.
    pub superset: Option<&'static str>,
    /// Python codec name for this encoding.
    pub python_codec: &'static str,
}

impl EncodingInfo {
    /// Deprecated alias for :attr:`is_multibyte_cjk`, kept for call sites
    /// written against the old field name.
    pub fn is_multibyte_cjk(&self) -> bool {
        self.is_multibyte_cjk
    }
}


/// Lookup table: canonical name and every alias -> entry.
pub static REGISTRY: Lazy<HashMap<&'static str, &'static EncodingInfo>> = Lazy::new(|| {
    let mut map: HashMap<&'static str, &'static EncodingInfo> = HashMap::new();
    for enc in ENCODING_ENTRIES.iter() {
        map.insert(enc.name, enc);
        for alias in enc.aliases.iter() {
            map.entry(*alias).or_insert(enc);
        }
    }
    map
});

/// Canonical entries, one per encoding (registry order).
pub fn entries() -> &'static [EncodingInfo] {
    ENCODING_ENTRIES
}

/// Get candidates for the given era, without include/exclude filters.
pub fn get_candidates(era: EncodingEra) -> Vec<&'static EncodingInfo> {
    get_candidates_filtered(era, None, None)
}

/// Get candidates matching era, include, and exclude filters in that order.
pub fn get_candidates_filtered(
    era: EncodingEra,
    include_encodings: Option<&HashSet<String>>,
    exclude_encodings: Option<&HashSet<String>>,
) -> Vec<&'static EncodingInfo> {
    let mut candidates: Vec<&'static EncodingInfo> = ENCODING_ENTRIES
        .iter()
        .filter(|enc| enc.era.contains(era))
        .collect();

    if let Some(include) = include_encodings {
        candidates.retain(|enc| include.contains(enc.name));
    }
    if let Some(exclude) = exclude_encodings {
        candidates.retain(|enc| !exclude.contains(enc.name));
    }
    candidates
}

